// Builds public/worldmap.js: a single SVG path of the world's land, drawn once from Natural Earth
// (public domain, via the world-atlas package) so the app never calls an outside map service.
// Projection: equirectangular, 1000 × 500 units, so lon/lat → x/y is simple maths in the browser:
//   x = (lon + 180) × 1000/360,  y = (90 − lat) × 1000/360
//
// Re-run only if you want a different level of detail:
//   mkdir /tmp/mapgen && cd /tmp/mapgen && npm i world-atlas@2.0.2 topojson-client@3.1.0 topojson-simplify@3.0.3 d3-geo@3.1.1
//   node /path/to/ankur/scripts/build-worldmap.mjs /tmp/mapgen
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const modDir = process.argv[2];
if (!modDir) { console.error('usage: node build-worldmap.mjs <dir with node_modules>'); process.exit(1); }
const req = createRequire(path.join(path.resolve(modDir), 'x.js'));
const { feature } = req('topojson-client');
const { presimplify, simplify, quantile } = req('topojson-simplify');
const { geoEquirectangular, geoPath } = await import(req.resolve('d3-geo'));
// 1:50m keeps small places like Singapore island; simplifying to the 10% quantile keeps the file ~100 KB.
let land = presimplify(req('world-atlas/land-50m.json'));
land = simplify(land, quantile(land, 0.1));

const projection = geoEquirectangular().scale(1000 / (2 * Math.PI)).translate([500, 250]);
const d = geoPath(projection)(feature(land, land.objects.land))
  .replace(/(\d+\.\d)\d+/g, '$1') // 0.1 unit ≈ 4 km at the equator: plenty for a map of universities
  .split('M').filter((ring) => new Set(ring.replace(/Z$/, '').split('L')).size > 2).map((ring) => `M${ring}`).join(''); // drop rings that collapsed to a dot

// Singapore is too small for the world outline, so it gets its own detailed outline (1:10m), clipped to the island.
const sgBox = [[103.55, 1.5], [104.1, 1.15]].map(([lon, lat]) => projection([lon, lat]));
const land10 = req('world-atlas/land-10m.json');
const sg = geoPath(geoEquirectangular().scale(1000 / (2 * Math.PI)).translate([500, 250]).clipExtent(sgBox))(feature(land10, land10.objects.land))
  .replace(/(\d+\.\d{3})\d+/g, '$1')
  // Clipping can add a ring that is just the clip box (a quirk of island winding in the source data); it would paint the sea as land.
  .split('M').filter((ring) => ring && ring.replace(/Z$/, '').split('L').length > 5).map((ring) => `M${ring}`).join('');

const out = path.join(path.dirname(new URL(import.meta.url).pathname), '..', 'public', 'worldmap.js');
fs.writeFileSync(out, `/* Land outline from Natural Earth (public domain) via world-atlas. Generated by scripts/build-worldmap.mjs — do not edit. */\nwindow.ANKUR_WORLD = ${JSON.stringify(d)};\nwindow.ANKUR_WORLD_SG = ${JSON.stringify(sg)};\n`);
console.log(`wrote ${out} (${(fs.statSync(out).size / 1024).toFixed(0)} KB)`);
